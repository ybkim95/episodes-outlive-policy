"""Sampler/trainer loop with controlled, per-turn staleness.

Each training batch is generated by a mix of past trainer weights, chosen per episode and per turn by
staleness(): a constant lag, plus (U > 0) U-turn segments so earlier turns of an episode come from older
weights, plus (qmax > 0) a heavy-tailed per-episode queue delay. Past weights live in a ring buffer, so
staleness is exact and runs are reproducible. sync=True samples with the trainer's own weights and is the
reference that lag=0 must match bit for bit.
Writes runs/<name>/{config.json, metrics.jsonl, trajectories.txt}.
"""
import argparse
import copy
import hashlib
import json
import time
from collections import deque
from dataclasses import asdict, dataclass, fields, replace
from pathlib import Path

import numpy as np
import torch
from torch import nn

from credit import CREDIT
from env import N_GOALS, TOK, VOCAB, MemoryDialogue
from offpolicy import drift_stats, loss, tree_advantages, tree_loss, turn_kl_penalty
from policy import Policy, act, score
from traj import Rollout, build_context, max_context_len

EVAL_SEED = 10**6  # held-out episode stream; training seeds are small ints
HERE = Path(__file__).parent


@dataclass
class Config:
    H: int = 16
    W: int = 16
    p_shift: float = 0.5
    cost: float = 0.01
    lag: int = 0
    U: int = 0
    qmax: int = 0
    sync: bool = False
    credit: str = "A0"
    objective: str = "none"
    clip: float = 0.2
    beta: float = 0.3  # chosen on tuning seed 100 at H=16 (sweep: 0.03, 0.1, 0.3, 1.0)
    beta1: float = 1.0
    drift_budget: float = 0.0  # > 0: beta is a Lagrange multiplier on per-token KL, set by dual ascent
    drift_per_turn: bool = False  # one multiplier per staleness bucket instead of one for the batch
    beta_lr: float = 1.0
    turn_penalty_lr: float = 0.0  # > 0: keep beta global, add a separate KL penalty per staleness bucket (E7)
    beta_path: str = ""  # control: replay the scalar beta of runs/<beta_path> per iteration instead of dual ascent
    branch: int = 4  # objective=tree/tree_flat/tree_ppo: continuations per trunk; group_size is then trunks per seed
    tree_no_level1: bool = False  # control: Branched CORO without level 1 (sibling contrast only)
    fork_resample: bool = False  # control: forked siblings redraw the pending goal shift (no shared user future)
    crn: bool = False  # control: the episodes of a flat CORO group share one goal-shift schedule, as siblings do
    minibatches: int = 1  # control: split each batch into this many whole-group steps, so later steps see l != 0
    groups: int = 32
    group_size: int = 8
    iters: int = 300
    lr: float = 1e-3
    seed: int = 100
    eval_every: int = 10
    eval_episodes: int = 512
    device: str = "cpu"
    out: str = "runs"
    name: str = ""


def staleness(cfg, rng, B):
    """(B, H) number of trainer updates between generating each turn and training on it."""
    s = np.full((B, cfg.H), cfg.lag)
    if cfg.U:
        seg = np.arange(cfg.H) // cfg.U
        s = s + (seg[-1] - seg)[None]
    if cfg.qmax:
        w = (np.arange(cfg.qmax + 1) + 1.0) ** -1.5
        s = s + rng.choice(cfg.qmax + 1, B, p=w / w.sum())[:, None]
    return s


def max_staleness(cfg):
    return cfg.lag + ((cfg.H - 1) // cfg.U if cfg.U else 0) + cfg.qmax


def rollout(policy_for, cfg, goals, rng, gen, stal, branch=(0, 1), crn=1, fork_rng=None):
    """policy_for(s) -> sampler weights s updates old; stal (B, H) picks them per episode and turn.
    branch=(b, k): after a shared prefix of b turns every episode forks into k continuations from the
    same state (rows grouped per parent), so B parents return B*k episodes. Version is relative (-stal)."""
    dev = next(policy_for(0).parameters()).device
    B, H = len(goals), cfg.H
    env = MemoryDialogue(goals, H, rng, p_shift=cfg.p_shift, cost=cfg.cost, crn=crn)
    obs, obs_hist, act_hist, ctxs = env.reset(), [], [], []
    acts, logps = np.zeros((B, H, 2), np.int64), np.zeros((B, H, 2), np.float32)
    mems, rew = np.zeros((B, H), np.int64), np.zeros((B, H), np.float32)
    b, k = branch
    for t in range(H):
        if t == b and k > 1:
            env.fork(k, fork_rng)
            rep = lambda x: np.repeat(x, k, axis=0)  # noqa: E731
            obs, stal, goals, acts, logps, mems, rew = map(rep, (obs, stal, goals, acts, logps, mems, rew))
            obs_hist, act_hist, ctxs = [rep(x) for x in obs_hist], [rep(x) for x in act_hist], [rep(x) for x in ctxs]
            B *= k
        obs_hist.append(obs)
        ctx = build_context(env.mem, obs_hist, act_hist, cfg.W)
        ctx_t = torch.as_tensor(ctx, device=dev)
        for s in np.unique(stal[:, t]):
            rows = np.nonzero(stal[:, t] == s)[0]
            a, lp = act(policy_for(s), ctx_t[torch.as_tensor(rows, device=dev)], gen)
            acts[rows, t], logps[rows, t] = a.cpu().numpy(), lp.cpu().numpy()
        ctxs.append(ctx)
        mems[:, t] = env.mem
        obs, rew[:, t], _ = env.step(acts[:, t])
        act_hist.append(np.concatenate([np.full((B, 1), TOK["<agent>"]), acts[:, t]], 1))
    return Rollout(ctxs, acts, logps, mems, rew, np.asarray(goals), -stal, branch)


def score_chunks(model, ro, max_tokens=2**18):
    """Yield (turns, (B, n, 2) log-probs of their stored actions); equal-length contexts share a forward."""
    dev = next(model.parameters()).device
    B = ro.act.shape[0]
    by_len = {}
    for t, c in enumerate(ro.ctx):
        by_len.setdefault(c.shape[1], []).append(t)
    for L, ts in by_len.items():
        step = max(1, max_tokens // (B * L))
        for i in range(0, len(ts), step):
            chunk = ts[i : i + step]
            ctx = torch.as_tensor(np.concatenate([ro.ctx[t] for t in chunk]), device=dev)
            a = torch.as_tensor(ro.act[:, chunk].transpose(1, 0, 2).reshape(-1, 2), device=dev)
            yield chunk, score(model, ctx, a).view(len(chunk), B, 2).transpose(0, 1)


def score_rollout(model, ro):
    """(B, H, 2) log-probs of stored actions (keeps the graph if grad is enabled)."""
    B, H = ro.act.shape[:2]
    out = torch.empty(B, H, 2, device=next(model.parameters()).device)
    for chunk, lp in score_chunks(model, ro):
        out[:, chunk] = lp
    return out


def backward_two_pass(model, ro, loss_of_logp):
    """Exact gradient with one chunk of activations alive at a time. Every objective depends on the
    policy only through the stored actions' log-probs, so: score without grad, get g = dL/dlogp on a
    detached copy, then re-score chunk by chunk and backprop sum(g * logp). (Keeping the whole graph
    needs O(H^3) attention memory at full context: ~40 GB at H=64.) Returns (loss, detached logp)."""
    with torch.no_grad():
        logp = score_rollout(model, ro)
    lp = logp.clone().requires_grad_()
    lossv = loss_of_logp(lp)
    lossv.backward()
    for chunk, lpc in score_chunks(model, ro):
        (lpc * lp.grad[:, chunk]).sum().backward()
    return lossv.detach(), logp


@torch.no_grad()
def evaluate(model, cfg, n=None):
    dev = next(model.parameters()).device
    rng, gen = np.random.default_rng(EVAL_SEED), torch.Generator(device=dev).manual_seed(EVAL_SEED)
    n = n or cfg.eval_episodes
    return rollout(lambda s: model, cfg, rng.integers(0, N_GOALS, n), rng, gen, np.zeros((n, cfg.H), int))


def render(ro, i, adv=None):
    """Human-readable dump of episode i: what the policy saw this turn and what it did."""
    lines = [f"goal=G{ro.goal[i]} return={ro.ret[i]:+.2f}"]
    for t, c in enumerate(ro.ctx):
        obs = " ".join(VOCAB[x] for x in c[i, -4:-1])
        a = " ".join(VOCAB[x] for x in ro.act[i, t])
        extra = f" adv={adv[i, t]:+.2f}" if adv is not None else ""
        lines.append(f"t={t:3d} v={ro.version[i, t]:+d} mem={VOCAB[ro.mem[i, t]]:4s} | {obs:22s} -> {a:12s} "
                     f"logp={ro.logp[i, t].sum():+.2f} r={ro.reward[i, t]:+.2f}{extra}")
    return "\n".join(lines)


TRAINING_CODE = ("credit.py", "env.py", "offpolicy.py", "policy.py", "runner.py", "traj.py")


def src_hash():
    """Hash of the code that can change a run. (Before the controls it hashed every .py, analysis scripts
    included, so it changed between stages even when training code did not.)"""
    h = hashlib.sha256()
    for name in TRAINING_CODE:
        h.update((HERE / name).read_bytes())
    return h.hexdigest()[:12]


def train(cfg, log=True):
    torch.manual_seed(cfg.seed)
    dev = torch.device(cfg.device)
    rng, gen = np.random.default_rng(cfg.seed), torch.Generator(device=dev).manual_seed(cfg.seed)
    model = Policy(max_context_len(cfg.H, cfg.W)).to(dev)
    opt = torch.optim.Adam(model.parameters(), lr=cfg.lr)
    past = deque(maxlen=max_staleness(cfg) + 1)  # past[-1-s] = trainer weights from s updates ago
    B, H = cfg.groups * cfg.group_size, cfg.H
    beta = np.full(max_staleness(cfg) + 1, cfg.beta)  # beta[s] weights turns that are s updates stale
    assert cfg.turn_penalty_lr == 0 or cfg.drift_budget > 0, "the per-turn penalty needs a drift budget"
    lam = np.zeros(max_staleness(cfg) + 1)  # lam[s]: KL-penalty multiplier for turns s updates stale
    beta_path = None
    if cfg.beta_path:
        beta_path = [json.loads(x)["beta"] for x in open(HERE / cfg.out / cfg.beta_path / "metrics.jsonl")]
        assert len(beta_path) >= cfg.iters and not cfg.drift_per_turn

    run_dir = None
    if log:
        name = cfg.name or f"{cfg.objective}_H{H}_W{cfg.W}_k{cfg.lag}_U{cfg.U}_q{cfg.qmax}_s{cfg.seed}"
        run_dir = HERE / cfg.out / name
        run_dir.mkdir(parents=True, exist_ok=True)
        (run_dir / "config.json").write_text(json.dumps({**asdict(cfg), "src_hash": src_hash(), "torch": torch.__version__}, indent=1))
        (run_dir / "metrics.jsonl").write_text("")

    metrics, t0, env_steps = [], time.time(), 0
    fork_rng = np.random.default_rng([cfg.seed, 1]) if cfg.fork_resample else None  # own stream: stays paired

    def update(sub, loss_of_logp):
        lv, lp = backward_two_pass(model, sub, loss_of_logp)
        g = nn.utils.clip_grad_norm_(model.parameters(), 1.0)
        opt.step()
        opt.zero_grad()
        return lv, lp, g

    for it in range(cfg.iters):
        goals = np.repeat(rng.integers(0, N_GOALS, cfg.groups), cfg.group_size)
        if cfg.sync:
            stal = np.zeros((B, H), int)
            policy_for = lambda s: model  # noqa: E731
        else:
            past.append(copy.deepcopy(model))
            stal = np.minimum(staleness(cfg, rng, B), len(past) - 1)  # early on, the oldest weights we have
            policy_for = lambda s: past[-1 - s]  # noqa: E731
        if beta_path:
            beta[:] = beta_path[it]
        tree = cfg.objective in ("tree", "tree_flat", "tree_ppo")  # tree_flat: same forked data, plain CORO over all
        # leaves of a seed; tree_ppo: same forked data, PPO-clip on the advantages the two levels imply
        branch = (int(rng.integers(1, H)), cfg.branch) if tree else (0, 1)  # branch turn drawn per batch
        assert not (tree and cfg.crn) and (tree or not (cfg.fork_resample or cfg.tree_no_level1))
        ro = rollout(policy_for, cfg, goals, rng, gen, stal, branch, crn=cfg.group_size if cfg.crn else 1, fork_rng=fork_rng)
        ro.version = it + ro.version
        turns = B * branch[0] + B * branch[1] * (H - branch[0])  # shared prefixes are generated once
        adv = torch.as_tensor(CREDIT[cfg.credit](ro, cfg), device=dev)
        beh = torch.as_tensor(ro.logp, device=dev)
        stal_turn = it - ro.version  # (B', H), forked rows included
        w = torch.as_tensor(beta[stal_turn], dtype=torch.float32, device=dev)
        lam_w = torch.as_tensor(lam[stal_turn], dtype=torch.float32, device=dev)
        pen = (lambda lp: turn_kl_penalty(lp, beh, lam_w)) if cfg.turn_penalty_lr > 0 else (lambda lp: 0.0)
        if cfg.objective == "tree":
            rew = torch.as_tensor(ro.reward, device=dev)
            lossv, logp, gn = update(ro, lambda lp: tree_loss(cfg, lp, beh, rew, branch, w) + pen(lp))
        else:
            ret = torch.as_tensor(ro.ret, device=dev)
            if cfg.objective == "tree_ppo":
                adv = torch.as_tensor(tree_advantages(ro.reward, branch, cfg.group_size), device=dev)
                lcfg = replace(cfg, objective="ppo")
            else:
                lcfg = replace(cfg, objective="coro", group_size=cfg.group_size * branch[1]) if tree else cfg
            if cfg.minibatches == 1:
                lossv, logp, gn = update(ro, lambda lp: loss(lcfg, lp, beh, adv, ret, w) + pen(lp))
            else:  # several steps per batch: from the second step on, the stored log-probs are behind the trainer
                n = len(ro.act) // cfg.minibatches
                assert not tree and cfg.turn_penalty_lr == 0 and n * cfg.minibatches == len(ro.act) and n % cfg.group_size == 0
                outs = [update(ro.rows(sl), lambda lp, sl=sl: loss(lcfg, lp, beh[sl], adv[sl], ret[sl], w[sl]))
                        for sl in (slice(j * n, (j + 1) * n) for j in range(cfg.minibatches))]
                lossv, logp, gn = (torch.stack([o[0] for o in outs]).mean(), torch.cat([o[1] for o in outs]),
                                   torch.stack([o[2] for o in outs]).mean())

        env_steps += turns
        m = dict(iter=it, staleness=float(stal.mean()), staleness_max=int(stal.max()), env_steps=env_steps, branch_turn=branch[0],
                 wall=time.time() - t0, loss=lossv.item(), grad_norm=gn.item(), beta=float(beta.mean()),
                 beta_by_stal=beta.round(4).tolist(),
                 train_return=float(ro.ret.mean()), train_goal=float(ro.reward[:, -1].mean()),
                 **drift_stats(logp, beh, cfg.group_size))
        if cfg.drift_budget > 0:  # dual ascent: tighten wherever the trainer has drifted past the budget
            lr_tok = (logp - beh).detach()
            kl_turn = (lr_tok.exp() - 1 - lr_tok).mean(2).cpu().numpy()  # (B', H) per-turn k3
            kl_by_stal = np.full(len(lam), np.nan)
            for s in np.unique(stal_turn):
                kl_by_stal[s] = kl_turn[stal_turn == s].mean()
            m["kl_by_stal"] = [None if np.isnan(x) else float(x) for x in kl_by_stal]
            if cfg.turn_penalty_lr > 0:
                m["lam_by_stal"] = lam.round(4).tolist()  # values used for this update
                for s in np.unique(stal_turn):
                    lam[s] = max(0.0, lam[s] + cfg.turn_penalty_lr * (kl_by_stal[s] - cfg.drift_budget))
            if cfg.drift_per_turn:
                for s in np.unique(stal_turn):
                    beta[s] = max(1e-3, beta[s] + cfg.beta_lr * (kl_turn[stal_turn == s].mean() - cfg.drift_budget))
            elif not beta_path:
                beta[:] = max(1e-3, beta[0] + cfg.beta_lr * (m["kl_k3"] - cfg.drift_budget))
        if it % cfg.eval_every == 0 or it == cfg.iters - 1:
            ev = evaluate(model, cfg)
            m["eval_return"], m["eval_goal"] = float(ev.ret.mean()), float(ev.reward[:, -1].mean())
            if log:
                print(f"it={it:4d} steps={m['env_steps']:>9d} train={m['train_return']:+.3f} eval={m['eval_return']:+.3f} "
                      f"goal={m['eval_goal']:.3f} kl={m['kl_k3']:.1e} ess={m['ess_traj']:.2f} beta={m['beta']:.3f} {m['wall']:.0f}s", flush=True)
        metrics.append(m)
        if log:
            with open(run_dir / "metrics.jsonl", "a") as f:
                f.write(json.dumps(m) + "\n")

    if log:
        ev = evaluate(model, cfg, n=8)
        (run_dir / "trajectories.txt").write_text("\n\n".join(render(ev, i) for i in range(8)))
    return model, metrics


def parse_args():
    p = argparse.ArgumentParser()
    for f in fields(Config):
        if f.type is bool:
            p.add_argument(f"--{f.name}", action="store_true")
        else:
            p.add_argument(f"--{f.name}", type=type(f.default), default=f.default)
    return Config(**vars(p.parse_args()))


if __name__ == "__main__":
    train(parse_args())
